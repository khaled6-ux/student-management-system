CREATE TABLE IF NOT EXISTS students (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(100) NOT NULL CHECK(length(trim(name)) BETWEEN 1 AND 100),
 age SMALLINT NOT NULL CHECK(age BETWEEN 1 AND 120),
 major VARCHAR(100) NOT NULL CHECK(length(trim(major)) BETWEEN 1 AND 100),
 gpa NUMERIC(3,2) NOT NULL CHECK(gpa BETWEEN 0 AND 4),
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_students_name ON students(lower(name));
CREATE INDEX IF NOT EXISTS idx_students_major ON students(lower(major));
